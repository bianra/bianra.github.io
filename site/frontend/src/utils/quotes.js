/**
 * 获取今日一言 (按日期确定性选择)
 * @param {string} dateStr YYYY-MM-DD (本地日期)
 */
export function quoteOfDay(dateStr) {
  const key = `${dateStr}|bianra-quote`
  return QUOTES[fnv1a(key) % QUOTES.length]
}
